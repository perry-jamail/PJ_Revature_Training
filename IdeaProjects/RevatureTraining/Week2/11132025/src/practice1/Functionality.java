package practice1;

public class Functionality {
    int add(int num1, int num2) {
        return num1 + num2;
    }

    int subtract(int num1, int num2) {
        return num1 - num2;
    }

    int multiply(int num1, int num2) {
        return num1 * num2;
    }

    float divide(int num1, int num2) {
        return (float) num1 / num2;
    }
}
